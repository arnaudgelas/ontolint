"""Generate ``docs/rules.md`` from the catalogue, the registry and the per-rule test cases.

The reference is built, never hand-edited:

* every catalogue row appears, grouped by family;
* implemented rules get their metadata, the fix suggestion, a flagged example and a clean example
  taken from the first positive and negative case in ``tests/rule_cases/``, and the real message the
  linter emits for the flagged example;
* proposed rules are listed as TODO with the backend they are waiting for.

Regenerate with ``uv run python tests/rule_docs_generator.py``; ``tests/test_rule_docs.py`` fails when
the committed file is stale.
"""

from __future__ import annotations

import logging
import re
import sys
from collections import defaultdict
from collections.abc import Sequence
from pathlib import Path

from planned_rule_intents import INTENTS
from rule_cases import load_cases
from rule_harness import PREFIXES, Case, RuleCases, graph

from ontolint import Linter
from ontolint.catalogue import CatalogueRow, load_catalogue
from ontolint.models import RuleSpec
from ontolint.rules.registry import default_registry

DOC = Path(__file__).resolve().parent.parent / "docs" / "rules.md"
HEADER = """\
# Rule reference

This file is generated by `tests/rule_docs_generator.py`; do not edit it by hand.
Regenerate it with `uv run python tests/rule_docs_generator.py`.

Each implemented rule lists its severity, scope and fix, then a flagged example and a clean example
in Turtle together with the message the linter reports for the flagged one. Rules that are not yet
implemented are marked **TODO** with the backend they are waiting for; they cannot be selected and
never run (see `--list-rules`). The intended behaviour of a TODO rule is a draft from
`tests/planned_rule_intents.py`, not a final specification.

All examples assume these prefixes:

```turtle
{prefixes}```
"""


def _turtle(case: Case) -> str | None:
    """Return the Turtle of a case, or ``None`` when it is built programmatically."""
    return case.turtle.strip() if case.turtle.strip() else None


def _first_message(rule_id: str, case: Case) -> str | None:
    """Return the first message emitted for ``rule_id`` on ``case`` (``None`` when nothing is emitted)."""
    if case.probe is not None:
        return None
    data = case.build() if case.build else graph(case.turtle)
    shapes = graph(case.shapes) if case.shapes is not None else None
    findings = Linter(data, shapes, **case.options).execute([rule_id]).findings
    # Blank-node labels are random per parse; keep the generated file reproducible.
    return re.sub(r"_:n[0-9a-f]{20,}", "_:b", findings[0].message) if findings else None


def _block(label: str, case: Case) -> list[str]:
    """Render one example (data and optional shapes) as fenced Turtle."""
    turtle = _turtle(case)
    if turtle is None and case.shapes is None:
        return [f"*{label}:* `{case.name}` (built programmatically; see `tests/rule_cases/`)", ""]
    lines = [f"*{label}:* {case.name}", ""]
    if turtle is not None:
        lines += ["```turtle", turtle, "```", ""]
    if case.shapes is not None:
        lines += ["Shapes graph:", "", "```turtle", case.shapes.strip(), "```", ""]
    if case.options:
        options = ", ".join(f"`{key}={value!r}`" for key, value in sorted(case.options.items()))
        lines += [f"Linter options: {options}.", ""]
    return lines


def _implemented(spec: RuleSpec, cases: RuleCases | None) -> list[str]:
    """Render the full entry of an implemented rule."""
    lines = [
        f"#### {spec.rule_id}: {spec.title}",
        "",
        f"- **Severity:** {spec.severity.value}",
        f"- **Scope:** {spec.scope.value}",
        f"- **Category:** {spec.category}",
        f"- **Fix:** {spec.suggestion}",
        "",
    ]
    if cases is None or not cases.positive:
        return lines + ["*No example available.*", ""]
    flagged = cases.positive[0]
    lines += _block("Flagged", flagged)
    message = _first_message(spec.rule_id, flagged)
    if message is not None:
        lines += [f"Reported: `{message}`", ""]
    if cases.negative:
        lines += _block("Clean", cases.negative[0])
    return lines


def _proposed(row: CatalogueRow) -> str:
    """Render one TODO table row for a rule that is not implemented yet."""
    intent = INTENTS[row.rule_id].replace("|", "\\|")
    return f"| {row.rule_id} | TODO | {intent} | {row.backend} | {row.test_requirement} |"


def build() -> str:
    """Return the full text of ``docs/rules.md``."""
    registry = default_registry()
    cases = load_cases()
    rows = load_catalogue()
    by_family: dict[str, list[CatalogueRow]] = defaultdict(list)
    for row in rows:
        by_family[row.family].append(row)
    implemented = sum(1 for row in rows if row.status.value == "implemented")
    lines = [HEADER.format(prefixes=PREFIXES), ""]
    lines += [
        f"**{implemented} of {len(rows)} catalogue rules are implemented; {len(rows) - implemented} are TODO.**",
        "",
        "| Family | Implemented | TODO |",
        "| --- | --- | --- |",
    ]
    for family in sorted(by_family):
        done = sum(1 for row in by_family[family] if row.status.value == "implemented")
        lines.append(f"| [{family}](#{family.lower()}) | {done} | {len(by_family[family]) - done} |")
    lines.append("")
    for family in sorted(by_family):
        lines += [f"## {family}", ""]
        todo = [row for row in by_family[family] if row.status.value != "implemented"]
        for row in by_family[family]:
            if row.status.value == "implemented":
                lines += _implemented(registry.get(row.rule_id), cases.get(row.rule_id))
        if todo:
            lines += [
                f"### {family}: TODO (to be implemented)",
                "",
                "| Rule | Status | Intended behaviour (draft) | Waiting for | Test requirement |",
                "| --- | --- | --- | --- | --- |",
                *[_proposed(row) for row in todo],
                "",
            ]
    return "\n".join(lines).rstrip() + "\n"


def main(argv: Sequence[str]) -> int:
    """Write the reference, or with ``--check`` only report whether the file is current."""
    logging.getLogger("rdflib").setLevel(logging.ERROR)  # odd-IRI examples make rdflib warn
    text = build()
    if "--check" in argv:
        return 0 if DOC.read_text(encoding="utf-8") == text else 1
    DOC.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
