MODULES_INTRO = """\
The docstring of each module that implements a rule of this page: the definitions that its rules'
specifications share. Each rule's own specification is shown under the rule."""

# A rule's specification is a top-level bullet of a module docstring, ``* **OWL001.** text``, or
# ``* **OWL005 / OWL006.** text`` for one shared by two rules, continued on lines indented two spaces.
SPEC_BULLET = re.compile(r"\* \*\*(?P<ids>[A-Z]+\d{3}(?: / [A-Z]+\d{3})*)\.\*\*(?: (?P<first>.*))?")
NEAR_BULLET = re.compile(r"\* \*\*[A-Z]+\d{3}")  # a header that SPEC_BULLET misses would lose its text
ROLE = re.compile(r":[a-z]+:`~?\.?(?P<target>[^`]+)`")  # :mod:`ontolint.ownership`, :func:`~.support.x`
# A CommonMark code span: a backtick run, then text, then the next run of exactly as many backticks.
CODE_SPAN = re.compile(r"(?<!`)(`+)(?!`).*?(?<!`)\1(?!`)")
# A note starting like this would render as a heading, quote, list, fence, table, link reference
# definition or thematic break instead of as text (a ``<`` is escaped, see _markdown).  Notes are
# blank-separated and an item's text starts its own block, so none can be a setext underline.
BLOCK_START = re.compile(
    r"#{1,6}(?:[ \t]|$)|>|[-+*](?:[ \t]|$)|\d{1,9}[.)](?:[ \t]|$)|```|~~~|\||\[[^\]]*\]:"
    r"|(?:\*[ \t]*){3,}$|(?:-[ \t]*){3,}$|(?:_[ \t]*){3,}$"
)

type _Unit = tuple[str, list[str]]  # "spec", "item" or "paragraph", and its docstring lines


@dataclass(frozen=True)
class ModuleDoc:
    """What a rule module's docstring says, as Markdown."""

    name: str  # "owl"
    specs: Mapping[str, str]  # rule id -> its specification, reflowed to one paragraph, roles converted
    notes: tuple[str, ...]  # the rest, one line per paragraph or item, blocks blank-separated


def _kind(module: str, line: str) -> str | None:
    """Return ``spec`` or ``item`` for a line that starts a list item, else ``None``."""
    if SPEC_BULLET.fullmatch(line):
        return "spec"
    if NEAR_BULLET.match(line):
        raise ValueError(f"{module}: a specification bullet must start '* **ID.** ': {line!r}")
    return "item" if line.startswith("* ") else None


def _units(module: str, lines: Sequence[str]) -> list[_Unit]:
    """Split docstring lines into paragraphs and list items, a specification bullet being a ``spec`` item.

    An item runs on over the lines indented two spaces and ends at the first other line: a blank line,
    another item or an unindented paragraph.  A paragraph runs on to a blank line or an item.
    """
    units: list[_Unit] = []
    open_kind: str | None = None
    for line in lines:
        kind = _kind(module, line)
        if not line.strip():
            open_kind = None
        elif kind is not None or open_kind is None or (open_kind != "paragraph" and not line.startswith("  ")):
            open_kind = kind or "paragraph"
            units.append((open_kind, [line]))
        else:
            units[-1][1].append(line)
    return units


def _reflow(lines: Sequence[str]) -> str:
    """Join lines into one, with a single space at each line break and no other whitespace change."""
    return " ".join(part for line in lines if (part := line.strip(" ")))


def _markdown(text: str) -> str:
    """Return docstring text as Markdown: each Sphinx role becomes a code span of its target.

    Outside code spans, ``\\`` and ``<`` are escaped as in :func:`_prose`; inside, where a backslash
    would show, they are kept as they are.
    """

    def role(match: re.Match[str]) -> str:
        if "<" in match["target"]:
            raise ValueError(f"a Sphinx role with an explicit title cannot be rendered: {match[0]!r}")
        return _code(match["target"])

    converted = ROLE.sub(role, text)
    parts: list[str] = []
    start = 0
    for span in CODE_SPAN.finditer(converted):
        parts += [_prose(converted[start : span.start()]), span[0]]
        start = span.end()
    return "".join([*parts, _prose(converted[start:])])


def _note(module: str, lines: Sequence[str]) -> str:
    """Return a paragraph or item text as Markdown, refusing one that would not render as text."""
    text = _markdown(_reflow(lines))
    if BLOCK_START.match(text):
        raise ValueError(f"{module}: a docstring paragraph or item would not render as text: {text[:60]!r}")
    return text


def _specify(module: str, lines: Sequence[str], specs: dict[str, str]) -> list[str]:
    """Record a specification bullet's text under each rule it names; return those rule ids."""
    match = SPEC_BULLET.fullmatch(lines[0])
    assert match is not None  # _units made it a "spec" for that reason
    text = _markdown(_reflow([match["first"] or "", *lines[1:]]))
    ids = match["ids"].split(" / ")
    if not text:
        raise ValueError(f"{module}: the specification bullet of {match['ids']} is empty")
    for rule_id in ids:
        if rule_id in specs:
            raise ValueError(f"{module}: {rule_id} is specified twice")
        specs[rule_id] = text
    return ids


def read_module(module: ModuleType) -> ModuleDoc:
    """Read a rule module's docstring: each rule's specification bullet, and everything else as notes.

    In the notes, each paragraph and item is one line and blocks are separated by a blank line, so no
    paragraph can become the continuation of an item; a run of specification bullets becomes one line
    naming the rules they specify, since each is shown under its rule instead.
    """
    if not module.__doc__:
        raise ValueError(f"{module.__name__} has no docstring (Python run with -OO?): its specifications would vanish")
    specs: dict[str, str] = {}
    blocks: list[_Unit] = []  # for a "spec" block, the rule ids instead of lines
    for kind, lines in _units(module.__name__, inspect.cleandoc(module.__doc__).splitlines()):
        if kind == "spec":
            content = _specify(module.__name__, lines, specs)
        elif kind == "item":
            content = [f"* {_note(module.__name__, [lines[0][2:], *lines[1:]])}"]
        else:
            content = [_note(module.__name__, lines)]
        if blocks and kind != "paragraph" and blocks[-1][0] == kind:
            blocks[-1][1].extend(content)
        else:
            blocks.append((kind, content))
    notes: list[str] = []
    for kind, content in blocks:
        notes += ["", f"*Specified under each rule: {', '.join(content)}.*"] if kind == "spec" else ["", *content]
    return ModuleDoc(module_name(module), specs, tuple(notes[1:]))


def spec_modules() -> tuple[ModuleType, ...]:
    """Return every module of :mod:`ontolint.rules` that declares ``SPECS``, in name order.

    These are the rule-family modules and those declaring rules that no graph module runs
    (``external``, ``safe_loader``), so a new one is found without a change here.
    """
    names = sorted(info.name for info in pkgutil.iter_modules(rule_package.__path__))
    modules = [importlib.import_module(f"{rule_package.__name__}.{name}") for name in names]
    return tuple(module for module in modules if hasattr(module, "SPECS"))


def specifications(docs: Sequence[ModuleDoc]) -> dict[str, tuple[str, str]]:
    """Return each specified rule's home module and specification, refusing a rule specified twice."""
    found: dict[str, tuple[str, str]] = {}
    for doc in docs:
        for rule_id, text in doc.specs.items():
            if rule_id in found:
                raise ValueError(f"{rule_id} is specified in both {found[rule_id][0]} and {doc.name}")
            found[rule_id] = (doc.name, text)
    return found


@dataclass(frozen=True)
class _Sources:
    """What the pages are built from, besides the catalogue."""

    registry: RuleRegistry
    cases: Mapping[str, RuleCases]
    docs: Mapping[str, ModuleDoc]  # by module name
    specs: Mapping[str, tuple[str, str]]  # rule id -> home module and specification
    declared: Mapping[str, str]  # rule id -> the module whose SPECS declare it

    def home(self, rule_id: str) -> str:
        """Return the module whose notes apply to a rule: the one with its bullet, else the one declaring it."""
        return self.specs[rule_id][0] if rule_id in self.specs else self.declared[rule_id]


def _turtle(case: Case) -> str | None:
    """Return the Turtle of a case, or ``None`` when it has none (built, probed or the empty graph)."""
    return case.turtle.strip() if case.turtle.strip() else None


def _one_line(text: str, what: str) -> str:
    """Return ``text``, refusing a line break: a code span cannot hold one without changing the page."""
    if "\n" in text or "\r" in text:
        raise ValueError(f"a rule case's {what} must fit on one line: {text!r}")
    return text


def _code(text: str) -> str:
    """Return ``text`` as a Markdown code span that nothing in it can close.

    The backtick run is one longer than the longest run inside; a space pads both ends when the text
    starts or ends with a backtick, or starts and ends with a space, since CommonMark strips one there.
    """
    if not text:
        raise ValueError("an empty text has no code span")
    ticks = "`" * (max((len(run) for run in re.findall(r"`+", text)), default=0) + 1)
    pad = " " if text[0] == "`" or text[-1] == "`" or (text[0] == text[-1] == " " and text.strip()) else ""
    return f"{ticks}{pad}{text}{pad}{ticks}"


def _prose(text: str) -> str:
    """Return catalogue or spec text for a Markdown line, escaping ``\\`` and ``<``.

    Unescaped, a placeholder such as ``.../obo/<id>.owl`` is an HTML tag, which github.com drops.
    """
    return text.replace("\\", "\\\\").replace("<", "\\<")


def _fence(text: str) -> list[str]:
    """Return ``text`` as a fenced Turtle block whose fence is longer than any backtick run inside."""
    fence = "`" * max(3, max((len(run) for run in re.findall(r"`+", text)), default=0) + 1)
    return [f"{fence}turtle", text, fence, ""]


def _first_message(rule_id: str, case: Case) -> str | None:
    """Return the first message emitted for ``rule_id`` on ``case`` (``None`` when nothing is emitted)."""
    if case.probe is not None:
        return None
    data = case.build() if case.build else graph(case.turtle)
    shapes = graph(case.shapes) if case.shapes is not None else None
    findings = Linter(data, shapes, **case.options).execute([rule_id]).findings
    # Blank-node labels are random per parse; keep the generated file reproducible.
    return re.sub(r"_:n[0-9a-f]{20,}", "_:b", findings[0].message) if findings else None


def _is_default(field: dataclasses.Field[Any], value: object) -> bool:
    """Whether a dataclass field has a default and ``value`` equals it (a required field never has one)."""
    if field.default is not dataclasses.MISSING:
        return bool(value == field.default)
    if field.default_factory is not dataclasses.MISSING:
        return bool(value == field.default_factory())
    return False


def _value(obj: object) -> str:
    """Return a compact, deterministic ``repr`` of a case option.

    A dataclass prints only its required fields and those that differ from their defaults, so a case
    shows the settings it chose and a new ``Policy`` field rewrites no page; containers recurse, and
    sets print sorted at every depth, so no item order depends on the hash seed.
    """
    if dataclasses.is_dataclass(obj) and not isinstance(obj, type):
        fields = [
            f"{field.name}={_value(value)}"
            for field in dataclasses.fields(obj)
            if not _is_default(field, value := getattr(obj, field.name))
        ]
        return f"{type(obj).__name__}({', '.join(fields)})"
    if isinstance(obj, (set, frozenset)):
        return _members(obj)
    if isinstance(obj, (tuple, list, dict)):
        return _items(obj)
    return repr(obj)


def _members(obj: set[object] | frozenset[object]) -> str:
    """Return the ``repr`` of a set with its members sorted by their own :func:`_value`."""
    if not obj:
        return f"{type(obj).__name__}()"
    listed = "{" + ", ".join(sorted(_value(item) for item in obj)) + "}"
    return listed if isinstance(obj, set) else f"{type(obj).__name__}({listed})"


def _items(obj: tuple[object, ...] | list[object] | dict[object, object]) -> str:
    """Return the ``repr`` of a tuple, list or dict with every element through :func:`_value`, in order."""
    if isinstance(obj, dict):
        return "{" + ", ".join(f"{_value(key)}: {_value(item)}" for key, item in obj.items()) + "}"
    inner = ", ".join(_value(item) for item in obj)
    if isinstance(obj, list):
        return f"[{inner}]"
    return f"({inner},)" if len(obj) == 1 else f"({inner})"


def _block(label: str, case: Case) -> list[str]:
    """Render one case: its name, how its graph is made (Turtle, built, probed or empty), shapes and options."""
    name = _code(_one_line(case.name, "case name"))
    if case.probe is not None:
        return [f"*{label}:* {name} (run through the command line or an adapter; see `tests/rule_cases/`)", ""]
    turtle = _turtle(case)
    if case.build is not None:
        lines = [f"*{label}:* {name} (built programmatically; see `tests/rule_cases/`)", ""]
    elif turtle is None:
        lines = [f"*{label}:* {name} (the empty data graph)", ""]
    else:
        lines = [f"*{label}:* {name}", "", *_fence(turtle)]
    if case.shapes is not None:
        lines += ["Shapes graph:", "", *_fence(case.shapes.strip())]
    if case.options:
        options = ", ".join(_code(f"{key}={_value(value)}") for key, value in sorted(case.options.items()))
        lines += [f"Linter options: {options}.", ""]
    return lines


def _implemented(spec: RuleSpec, sources: _Sources) -> list[str]:
    """Render the full entry of an implemented rule."""
    home = sources.home(spec.rule_id)
    lines = [
        f"#### {spec.rule_id}: {_prose(spec.title)}",
        "",
        f"- **Severity:** {spec.severity.value}",
        f"- **Scope:** {spec.scope.value}",
        f"- **Category:** {spec.category}",
        f"- **Module:** [{_code(home)}](#module-{home})",
        f"- **Fix:** {_prose(spec.suggestion)}",
    ]
    if is_pipeline(spec):
        lines.append(
            "- **Selectable:** no (a pipeline rule: it always applies, so `--select` and `--ignore` reject it)"
        )
    lines.append("")
    if spec.rule_id in sources.specs:
        lines += [f"**Specification.** {sources.specs[spec.rule_id][1]}", ""]
    else:
        lines += ["*No rule-level specification yet; see the module notes above.*", ""]
    cases = sources.cases.get(spec.rule_id)
    if cases is None or not cases.positive:
        return lines + ["*No example available.*", ""]
    for case in cases.positive:
        lines += _block("Flagged", case)
        message = _first_message(spec.rule_id, case)
        if message is not None:
            lines += [f"Reported: {_code(_one_line(message, 'message'))}", ""]
    for case in cases.negative:
        lines += _block("Clean", case)
    return lines


def _proposed(row: CatalogueRow) -> str:
    """Render one TODO table row for a rule that is not implemented yet."""
    intent = _prose(INTENTS[row.rule_id]).replace("|", "\\|")
    return f"| {row.rule_id} | TODO | {intent} | {_prose(row.backend)} | {_prose(row.test_requirement)} |"


def _page_name(family: str) -> str:
    """Return the path of a family page relative to ``docs/``."""
    return f"rules/{family.lower()}.md"


def _modules(rows: Sequence[CatalogueRow], sources: _Sources) -> list[str]:
    """Render the notes of every module home to an implemented rule of ``rows``, by module name."""
    homes = sorted({sources.home(row.rule_id) for row in rows if row.status.value == "implemented"})
    if not homes:
        return []
    lines = ["## Modules", "", MODULES_INTRO, ""]
    for name in homes:
        source = f"Source: `src/ontolint/rules/{name}.py`."
        lines += [f"### Module {name}", "", source, "", *sources.docs[name].notes, ""]
    return lines


def _family_page(family: str, rows: Sequence[CatalogueRow], sources: _Sources) -> str:
    """Return the text of one family page: its modules' notes, every implemented rule's entry, the TODOs."""
    lines = [PAGE_HEADER.format(family=family, prefixes=PREFIXES), *_modules(rows, sources), "## Rules", ""]
    for row in rows:
        if row.status.value == "implemented":
            lines += _implemented(sources.registry.get(row.rule_id), sources)
    todo = [row for row in rows if row.status.value != "implemented"]
    if todo:
        lines += [
            f"### {family}: TODO (to be implemented)",
            "",
            "| Rule | Status | Intended behaviour (draft) | Waiting for | Test requirement |",
            "| --- | --- | --- | --- | --- |",
            *[_proposed(row) for row in todo],
            "",
        ]
    return "\n".join(lines).rstrip() + "\n"


def _index_row(row: CatalogueRow, registry: RuleRegistry) -> str:
    """Render one index table row: the rule linked to its family page, its title and its severity."""
    severity = registry.get(row.rule_id).severity.value if row.status.value == "implemented" else "TODO"
    title = _prose(row.title).replace("|", "\\|")
    return f"| [{row.rule_id}]({_page_name(row.family)}) | {title} | {severity} |"


def _index(by_family: Mapping[str, Sequence[CatalogueRow]], registry: RuleRegistry) -> str:
    """Return the text of ``docs/rules.md``: the counts, then every family's rules linked to its page."""
    rows = [row for family in sorted(by_family) for row in by_family[family]]
    implemented = sum(1 for row in rows if row.status.value == "implemented")
    lines = [INDEX_HEADER.format(pipeline_help=PIPELINE_HELP), ""]
    lines += [
        f"**{implemented} of {len(rows)} catalogue rules are implemented; {len(rows) - implemented} are TODO.**",
        "",
        "| Family | Implemented | TODO |",
        "| --- | --- | --- |",
    ]
    for family in sorted(by_family):
        done = sum(1 for row in by_family[family] if row.status.value == "implemented")
        lines.append(f"| [{family}](#{family.lower()}) | {done} | {len(by_family[family]) - done} |")
    lines.append("")
    for family in sorted(by_family):
        lines += [
            f"## {family}",
            "",
            f"[Every {family} rule with its specification and cases]({_page_name(family)})",
            "",
            "| Rule | Title | Severity |",
            "| --- | --- | --- |",
            *[_index_row(row, registry) for row in by_family[family]],
            "",
        ]
    return "\n".join(lines).rstrip() + "\n"


def render(cases: Mapping[str, RuleCases], modules: Sequence[ModuleType]) -> dict[str, str]:
    """Return every page of the reference for these cases and spec modules, keyed by path under ``docs/``."""
    registry = default_registry()
    rows = load_catalogue()
    docs = [read_module(module) for module in modules]
    specs = specifications(docs)
    unknown = sorted(set(specs) - {row.rule_id for row in rows if row.status.value == "implemented"})
    if unknown:
        raise ValueError(f"specification bullets for rules that are not implemented catalogue rules: {unknown}")
    declared = {spec.rule_id: module_name(module) for module in modules for spec in module.SPECS}
    sources = _Sources(registry, cases, {doc.name: doc for doc in docs}, specs, declared)
    by_family: dict[str, list[CatalogueRow]] = defaultdict(list)
    for row in rows:
        by_family[row.family].append(row)
    pages = {"rules.md": _index(by_family, registry)}
    for family in sorted(by_family):
        pages[_page_name(family)] = _family_page(family, by_family[family], sources)
    return pages


def build() -> dict[str, str]:
    """Return every page of the reference, keyed by its path relative to ``docs/``."""
    return render(load_cases(), spec_modules())


def stale_pages(pages: Mapping[str, str], root: Path = DOCS) -> list[str]:
    """Name every page under ``root`` that differs from ``pages``, is missing, or is a Markdown orphan."""
    problems: list[str] = []
    for name, text in sorted(pages.items()):
        path = root / name
        if not path.is_file():
            problems.append(f"{name} (missing)")
        elif path.read_text(encoding="utf-8") != text:
            problems.append(f"{name} (stale)")
    for path in sorted((root / "rules").glob("*.md")):
        if f"rules/{path.name}" not in pages:
            problems.append(f"rules/{path.name} (orphan)")
    return problems


def write_pages(pages: Mapping[str, str], root: Path = DOCS) -> None:
    """Write every page under ``root`` and delete the Markdown files of ``root/rules`` it does not hold.

    Only ``*.md`` files are considered, so other files there (a ``.DS_Store``) are left alone.
    """
    (root / "rules").mkdir(parents=True, exist_ok=True)
    for name, text in pages.items():
        (root / name).write_text(text, encoding="utf-8")
    for path in (root / "rules").glob("*.md"):
        if f"rules/{path.name}" not in pages:
            path.unlink()


def main(argv: Sequence[str]) -> int:
    """Write the reference, or with ``--check`` only print the pages that are not current."""
    logging.getLogger("rdflib").setLevel(logging.ERROR)  # odd-IRI examples make rdflib warn
    pages = build()
    if "--check" in argv:
        stale = stale_pages(pages)
        for problem in stale:
            print(problem)
        return 1 if stale else 0
    write_pages(pages)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
