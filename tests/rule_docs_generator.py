"""Generate the rule reference from the catalogue, the registry and the per-rule test cases.

The reference is built, never hand-edited.  It is one index, ``docs/rules.md``, and one page per
catalogue family, ``docs/rules/<family>.md``, so that no page grows past what github.com renders:

* every catalogue row appears in the index, grouped by family and linked to its family page;
* on the family page, implemented rules get their metadata, the fix suggestion, a flagged example and
  a clean example taken from the first positive and negative case in ``tests/rule_cases/``, and the
  real message the linter emits for the flagged example;
* proposed rules are listed as TODO with the backend they are waiting for.

Regenerate with ``uv run python tests/rule_docs_generator.py``, which also deletes any other Markdown
file in ``docs/rules/``; ``tests/test_rule_docs.py`` fails when a page is stale, missing or not
generated.
"""

from __future__ import annotations

import logging
import re
import sys
from collections import defaultdict
from collections.abc import Mapping, Sequence
from pathlib import Path

from planned_rule_intents import INTENTS
from rule_cases import load_cases
from rule_harness import PREFIXES, Case, RuleCases, graph

from ontolint import Linter
from ontolint.catalogue import CatalogueRow, load_catalogue
from ontolint.models import RuleSpec
from ontolint.rules.registry import RuleRegistry, default_registry
from ontolint.selection import PIPELINE_HELP, is_pipeline

DOCS = Path(__file__).resolve().parent.parent / "docs"
DOC = DOCS / "rules.md"
PAGES = DOCS / "rules"
INDEX_HEADER = """\
# Rule reference

This file and the pages under `docs/rules/` are generated by `tests/rule_docs_generator.py`; do not
edit them by hand. Regenerate them with `uv run python tests/rule_docs_generator.py`.

This index lists every catalogue rule by family. Each family has its own page,
`docs/rules/<family>.md`, linked below. There each implemented rule lists its severity, scope and fix,
then a flagged example and a clean example in Turtle together with the message the linter reports for
the flagged one. Rules that are not yet implemented are marked **TODO** with the backend they are
waiting for; they cannot be selected and never run (see `--list-rules`). The intended behaviour of a
TODO rule is a draft from `tests/planned_rule_intents.py`, not a final specification.

Rules marked **Selectable: no** are pipeline rules, of backend `cli`
({pipeline_help}). They are implemented and always apply, so `--select` and `--ignore` reject them,
and `--list-rules --format json` reports them with `"selectable": false`.
"""
PAGE_HEADER = """\
# {family} rules

This page is generated by `tests/rule_docs_generator.py`; do not edit it by hand. Every Markdown file
in `docs/rules/` is generated, and regenerating them with `uv run python tests/rule_docs_generator.py`
deletes any other. How to read an entry is explained in the [rule reference index](../rules.md).

All examples assume these prefixes:

```turtle
{prefixes}```
"""


def _turtle(case: Case) -> str | None:
    """Return the Turtle of a case, or ``None`` when it is built programmatically."""
    return case.turtle.strip() if case.turtle.strip() else None


def _first_message(rule_id: str, case: Case) -> str | None:
    """Return the first message emitted for ``rule_id`` on ``case`` (``None`` when nothing is emitted)."""
    if case.probe is not None:
        return None
    data = case.build() if case.build else graph(case.turtle)
    shapes = graph(case.shapes) if case.shapes is not None else None
    findings = Linter(data, shapes, **case.options).execute([rule_id]).findings
    # Blank-node labels are random per parse; keep the generated file reproducible.
    return re.sub(r"_:n[0-9a-f]{20,}", "_:b", findings[0].message) if findings else None


def _block(label: str, case: Case) -> list[str]:
    """Render one example (data and optional shapes) as fenced Turtle."""
    turtle = _turtle(case)
    if turtle is None and case.shapes is None:
        return [f"*{label}:* `{case.name}` (built programmatically; see `tests/rule_cases/`)", ""]
    lines = [f"*{label}:* {case.name}", ""]
    if turtle is not None:
        lines += ["```turtle", turtle, "```", ""]
    if case.shapes is not None:
        lines += ["Shapes graph:", "", "```turtle", case.shapes.strip(), "```", ""]
    if case.options:
        options = ", ".join(f"`{key}={value!r}`" for key, value in sorted(case.options.items()))
        lines += [f"Linter options: {options}.", ""]
    return lines


def _implemented(spec: RuleSpec, cases: RuleCases | None) -> list[str]:
    """Render the full entry of an implemented rule."""
    lines = [
        f"#### {spec.rule_id}: {spec.title}",
        "",
        f"- **Severity:** {spec.severity.value}",
        f"- **Scope:** {spec.scope.value}",
        f"- **Category:** {spec.category}",
        f"- **Fix:** {spec.suggestion}",
    ]
    if is_pipeline(spec):
        lines.append(
            "- **Selectable:** no (a pipeline rule: it always applies, so `--select` and `--ignore` reject it)"
        )
    lines.append("")
    if cases is None or not cases.positive:
        return lines + ["*No example available.*", ""]
    flagged = cases.positive[0]
    lines += _block("Flagged", flagged)
    message = _first_message(spec.rule_id, flagged)
    if message is not None:
        lines += [f"Reported: `{message}`", ""]
    if cases.negative:
        lines += _block("Clean", cases.negative[0])
    return lines


def _proposed(row: CatalogueRow) -> str:
    """Render one TODO table row for a rule that is not implemented yet."""
    intent = INTENTS[row.rule_id].replace("|", "\\|")
    return f"| {row.rule_id} | TODO | {intent} | {row.backend} | {row.test_requirement} |"


def _page_name(family: str) -> str:
    """Return the path of a family page relative to ``docs/``."""
    return f"rules/{family.lower()}.md"


def _family_page(
    family: str, rows: Sequence[CatalogueRow], registry: RuleRegistry, cases: Mapping[str, RuleCases]
) -> str:
    """Return the text of one family page: every implemented rule's entry, then the TODO table."""
    lines = [PAGE_HEADER.format(family=family, prefixes=PREFIXES), "## Rules", ""]
    for row in rows:
        if row.status.value == "implemented":
            lines += _implemented(registry.get(row.rule_id), cases.get(row.rule_id))
    todo = [row for row in rows if row.status.value != "implemented"]
    if todo:
        lines += [
            f"### {family}: TODO (to be implemented)",
            "",
            "| Rule | Status | Intended behaviour (draft) | Waiting for | Test requirement |",
            "| --- | --- | --- | --- | --- |",
            *[_proposed(row) for row in todo],
            "",
        ]
    return "\n".join(lines).rstrip() + "\n"


def _index_row(row: CatalogueRow, registry: RuleRegistry) -> str:
    """Render one index table row: the rule linked to its family page, its title and its severity."""
    severity = registry.get(row.rule_id).severity.value if row.status.value == "implemented" else "TODO"
    title = row.title.replace("|", "\\|")
    return f"| [{row.rule_id}]({_page_name(row.family)}) | {title} | {severity} |"


def _index(by_family: Mapping[str, Sequence[CatalogueRow]], registry: RuleRegistry) -> str:
    """Return the text of ``docs/rules.md``: the counts, then every family's rules linked to its page."""
    rows = [row for family in sorted(by_family) for row in by_family[family]]
    implemented = sum(1 for row in rows if row.status.value == "implemented")
    lines = [INDEX_HEADER.format(pipeline_help=PIPELINE_HELP), ""]
    lines += [
        f"**{implemented} of {len(rows)} catalogue rules are implemented; {len(rows) - implemented} are TODO.**",
        "",
        "| Family | Implemented | TODO |",
        "| --- | --- | --- |",
    ]
    for family in sorted(by_family):
        done = sum(1 for row in by_family[family] if row.status.value == "implemented")
        lines.append(f"| [{family}](#{family.lower()}) | {done} | {len(by_family[family]) - done} |")
    lines.append("")
    for family in sorted(by_family):
        lines += [
            f"## {family}",
            "",
            f"[Every {family} rule in full]({_page_name(family)})",
            "",
            "| Rule | Title | Severity |",
            "| --- | --- | --- |",
            *[_index_row(row, registry) for row in by_family[family]],
            "",
        ]
    return "\n".join(lines).rstrip() + "\n"


def build() -> dict[str, str]:
    """Return every page of the reference, keyed by its path relative to ``docs/``."""
    registry = default_registry()
    cases = load_cases()
    by_family: dict[str, list[CatalogueRow]] = defaultdict(list)
    for row in load_catalogue():
        by_family[row.family].append(row)
    pages = {"rules.md": _index(by_family, registry)}
    for family in sorted(by_family):
        pages[_page_name(family)] = _family_page(family, by_family[family], registry, cases)
    return pages


def stale_pages(pages: Mapping[str, str], root: Path = DOCS) -> list[str]:
    """Name every page under ``root`` that differs from ``pages``, is missing, or is a Markdown orphan."""
    problems: list[str] = []
    for name, text in sorted(pages.items()):
        path = root / name
        if not path.is_file():
            problems.append(f"{name} (missing)")
        elif path.read_text(encoding="utf-8") != text:
            problems.append(f"{name} (stale)")
    for path in sorted((root / "rules").glob("*.md")):
        if f"rules/{path.name}" not in pages:
            problems.append(f"rules/{path.name} (orphan)")
    return problems


def write_pages(pages: Mapping[str, str], root: Path = DOCS) -> None:
    """Write every page under ``root`` and delete the Markdown files of ``root/rules`` it does not hold.

    Only ``*.md`` files are considered, so other files there (a ``.DS_Store``) are left alone.
    """
    (root / "rules").mkdir(parents=True, exist_ok=True)
    for name, text in pages.items():
        (root / name).write_text(text, encoding="utf-8")
    for path in (root / "rules").glob("*.md"):
        if f"rules/{path.name}" not in pages:
            path.unlink()


def main(argv: Sequence[str]) -> int:
    """Write the reference, or with ``--check`` only print the pages that are not current."""
    logging.getLogger("rdflib").setLevel(logging.ERROR)  # odd-IRI examples make rdflib warn
    pages = build()
    if "--check" in argv:
        stale = stale_pages(pages)
        for problem in stale:
            print(problem)
        return 1 if stale else 0
    write_pages(pages)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
