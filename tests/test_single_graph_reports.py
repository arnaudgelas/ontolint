"""Reports of files with only a default graph: the same in every RDF syntax, and pinned.

``tests/fixtures/datasets/single_graph.*`` hold one small, deliberately flawed ontology written in
every syntax ontolint reads: Turtle, N-Triples, RDF/XML, JSON-LD (a top-level ``@graph`` with no
``@id``), TriG (a ``{ }`` default graph block) and N-Quads (no graph term).  None of them has a
named graph, so whatever the loader learns about named graphs must leave their reports alone.

Two contracts guard that:

* a relative one: every twin's text, JSON and SARIF report equals the Turtle file's after its file
  name is substituted, except for SARIF regions, which follow each syntax's own layout;
* ``tests/golden/single_graph_reports.json``, an ordinary golden of every report and exit code,
  regenerated deliberately with ``ONTOLINT_UPDATE_GOLDEN=1`` (a new rule changes it).  It was first
  generated by the 0.10.2 code, before the loader recorded named graphs.  Regenerated for the
  coverage-gap retitles of OWL010, OWL032, OWL035, SHQ008 and ALIGN003: the JSON and SARIF reports
  carry every rule's title, and rendered before and after they were equal once each old title was
  replaced by its new one; the text reports and exit codes did not move.
"""

from __future__ import annotations

import hashlib
import json
import os
from pathlib import Path
from typing import Any

import pytest

from ontolint import main
from ontolint._version import package_version

FIXTURES = Path(__file__).parent / "fixtures" / "datasets"
GOLDEN = Path(__file__).parent / "golden" / "single_graph_reports.json"
UPDATE = os.environ.get("ONTOLINT_UPDATE_GOLDEN") == "1"
TWINS = ("nt", "rdf", "jsonld", "trig", "nq")
SYNTAXES = ("ttl", *TWINS)
FORMATS = ("text", "json", "sarif")
MAX_VERBATIM = 3000


def _report(
    extension: str, fmt: str, capsys: pytest.CaptureFixture[str], monkeypatch: pytest.MonkeyPatch
) -> tuple[int, str]:
    monkeypatch.chdir(FIXTURES)
    code = main([f"single_graph.{extension}", "--format", fmt])
    out = capsys.readouterr().out
    # The SARIF driver records the package version; a release must not invalidate the golden.
    return code, out.replace(f'"version": "{package_version()}"', '"version": "<version>"')


def _without_regions(node: Any) -> Any:
    """``node`` with every SARIF ``region`` removed (line and column depend on the syntax's layout)."""
    if isinstance(node, dict):
        return {key: _without_regions(value) for key, value in node.items() if key != "region"}
    if isinstance(node, list):
        return [_without_regions(value) for value in node]
    return node


@pytest.mark.parametrize("fmt", FORMATS)
@pytest.mark.parametrize("extension", TWINS)
def test_a_single_graph_file_reports_like_its_turtle_twin(
    extension: str, fmt: str, capsys: pytest.CaptureFixture[str], monkeypatch: pytest.MonkeyPatch
) -> None:
    turtle_code, turtle = _report("ttl", fmt, capsys, monkeypatch)
    code, report = _report(extension, fmt, capsys, monkeypatch)
    assert code == turtle_code
    report = report.replace(f"single_graph.{extension}", "single_graph.ttl")
    if fmt == "sarif":
        assert _without_regions(json.loads(report)) == _without_regions(json.loads(turtle))
    else:
        assert report == turtle


def _compact(text: str) -> str:
    """Keep small reports verbatim; larger ones are pinned by length and digest."""
    if len(text) <= MAX_VERBATIM:
        return text
    return f"sha256:{hashlib.sha256(text.encode('utf-8')).hexdigest()} ({len(text)} chars)"


def _compute(capsys: pytest.CaptureFixture[str], monkeypatch: pytest.MonkeyPatch) -> dict[str, Any]:
    snapshot: dict[str, Any] = {}
    for extension in SYNTAXES:
        for fmt in FORMATS:
            code, report = _report(extension, fmt, capsys, monkeypatch)
            snapshot[f"single_graph.{extension} {fmt}"] = {"exit": code, "stdout": _compact(report)}
    return snapshot


def test_regenerate_golden(capsys: pytest.CaptureFixture[str], monkeypatch: pytest.MonkeyPatch) -> None:
    """Opt-in: rewrite the snapshot from the current implementation."""
    if not UPDATE:
        pytest.skip("set ONTOLINT_UPDATE_GOLDEN=1 to regenerate the golden snapshot")
    GOLDEN.write_text(
        json.dumps(_compute(capsys, monkeypatch), indent=1, ensure_ascii=False, sort_keys=True) + "\n",
        encoding="utf-8",
    )


@pytest.mark.skipif(UPDATE, reason="regenerating golden snapshot")
def test_single_graph_reports_match_golden(capsys: pytest.CaptureFixture[str], monkeypatch: pytest.MonkeyPatch) -> None:
    assert _compute(capsys, monkeypatch) == json.loads(GOLDEN.read_text(encoding="utf-8"))
