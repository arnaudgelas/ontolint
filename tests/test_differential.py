def _fingerprint(rule: str, focus: str, message: str) -> str:
    payload = json.dumps([rule, focus, message], ensure_ascii=False, separators=(",", ":"))
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()


def _linter_snapshot(name: str) -> list[dict[str, str]]:
    graph_factory, shapes_factory, kwargs = LINTER_CASES[name]
    shapes = shapes_factory() if shapes_factory else None
    findings = Linter(graph_factory(), shapes, **kwargs).run()
    return [{**f.to_dict(), "fingerprint": _fingerprint(f.rule, f.focus, f.message)} for f in findings]


