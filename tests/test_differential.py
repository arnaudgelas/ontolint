def _compact(text: str) -> str:
    """Keep small reports verbatim; larger ones are pinned by length and digest."""
    if len(text) <= MAX_VERBATIM:
        return text
    return f"sha256:{hashlib.sha256(text.encode('utf-8')).hexdigest()} ({len(text)} chars)"


def _normalise(text: str, tmp: Path) -> str:
    text = text.replace(str(FIXTURES.resolve()), "<fixtures>").replace(str(FIXTURES), "<fixtures>")
    text = text.replace(str(tmp.resolve()), "<tmp>").replace(str(tmp), "<tmp>")
    # The SARIF driver records the package version; a release must not invalidate the golden.
    text = text.replace(f'"version": "{package_version()}"', '"version": "<version>"')
    return _compact(re.sub(r"/private(?=<)", "", text))


def _cli_snapshot(name: str, tmp: Path, capsys: pytest.CaptureFixture[str], monkeypatch: pytest.MonkeyPatch) -> Any:
    argv, robot = CLI_CASES[name]
    monkeypatch.chdir(FIXTURES)
    if robot is not None:
        # Pin docker availability so goldens do not depend on the machine running them.
        monkeypatch.setattr("ontolint.engine.shutil.which", lambda _: "docker" if robot >= 0 else None)
        monkeypatch.setattr("ontolint.ontolint.subprocess.run", _fake_robot(max(robot, 0)))
    out_file = tmp / "report.out"
    base_file = tmp / "baseline.json"
    results: dict[str, Any] = {}
    code = main([*argv, "--output", str(out_file)])
    captured = capsys.readouterr()
    results["to_file"] = {
        "exit": code,
        "stdout": _normalise(captured.out, tmp),
        "stderr": _normalise(captured.err, tmp),
        "file": _normalise(out_file.read_text(encoding="utf-8"), tmp) if out_file.exists() else None,
    }
    code = main(argv)
    captured = capsys.readouterr()
    results["to_stdout"] = {
        "exit": code,
        "stdout": _normalise(captured.out, tmp),
        "stderr": _normalise(captured.err, tmp),
    }
    if "json" in argv and "--list-rules" not in argv and "--explain" not in argv:
        results["legacy_json_view"] = _legacy_json_view(captured.out, tmp)
    if name in {"json_default", "json_shapes", "json_config", "json_clean"}:
        code = main([*argv, "--write-baseline", str(base_file)])
        fingerprints = json.loads(base_file.read_text(encoding="utf-8"))["fingerprints"]
        results["write_baseline"] = {"exit": code, "count": len(fingerprints)}
        code = main([*argv, "--baseline", str(base_file)])
        results["with_baseline"] = {"exit": code, "stdout": _normalise(capsys.readouterr().out, tmp)}
    return results


def _legacy_json_view(stdout: str, tmp: Path) -> str:
    """The JSON report reduced to the historical ``summary``/``findings`` keys, as the old CLI printed it."""
    document = json.loads(stdout)
    findings = [{k: v for k, v in f.items() if k not in ADDITIVE_FINDING_KEYS} for f in document["findings"]]
    legacy = json.dumps({"summary": document["summary"], "findings": findings}, indent=2) + "\n"
    return _normalise(legacy, tmp)


def _compute(tmp: Path, capsys: pytest.CaptureFixture[str], monkeypatch: pytest.MonkeyPatch) -> dict[str, Any]:
    snapshot: dict[str, Any] = {"linter": {name: _linter_snapshot(name) for name in LINTER_CASES}, "cli": {}}
    for name in CLI_CASES:
        case_dir = tmp / name
        case_dir.mkdir()
        snapshot["cli"][name] = _cli_snapshot(name, case_dir, capsys, monkeypatch)
    return snapshot


