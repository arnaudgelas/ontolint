"""Bump the ontolint version and generate the changelog entry; edit files only.

    uv run python scripts/bump_version.py {major|minor|patch|X.Y.Z} [--dry-run]

The version lives in ``pyproject.toml`` and, as a fallback for uninstalled use, in
``src/ontolint/_version.py`` (a test keeps them equal); ``uv.lock`` records it too, and the release workflow
pins the Action at it (``uses: arnaudgelas/ontolint@vX.Y.Z``).  The script rewrites
all four and prepends a section to ``CHANGELOG.md``, built from the conventional-commit subjects since the
previous ``vX.Y.Z`` tag.  It never commits, tags or pushes: review the diff, then commit and tag yourself.
Pushing the tag publishes to PyPI (``.github/workflows/release.yml``).
"""

# ruff: noqa: S603, S607 -- every subprocess call has a fixed argv: git and uv are the tools being driven.

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from collections import defaultdict
from collections.abc import Callable, Sequence
from dataclasses import dataclass
from datetime import date
from pathlib import Path

VERSION = re.compile(r"(\d+)\.(\d+)\.(\d+)")
TAG = re.compile(r"v(\d+)\.(\d+)\.(\d+)")
PYPROJECT_LINE = re.compile(r'^version = "([^"]+)"$', re.MULTILINE)
FALLBACK_LINE = re.compile(r'^FALLBACK_VERSION = "([^"]+)"$', re.MULTILINE)
RELEASE_WORKFLOW = ".github/workflows/release.yml"
ACTION_PIN = re.compile(r"(?<=uses: arnaudgelas/ontolint@v)\d+\.\d+\.\d+")
SUBJECT = re.compile(r"(?P<type>[a-z]+)(?:\((?P<scope>[^)]*)\))?(?P<bang>!)?: (?P<text>.+)")
CHANGELOG_HEADER = "# Changelog\n\nAll notable changes to ontolint, generated by `scripts/bump_version.py`.\n"
SECTIONS = (
    ("breaking", "Breaking changes"),
    ("feat", "Added"),
    ("fix", "Fixed"),
    ("perf", "Performance"),
    ("docs", "Documentation"),
    ("other", "Maintenance"),
)
OTHER_TYPES = frozenset({"test", "ci", "chore", "build", "refactor", "style", "revert"})
NOT_IN_CHANGELOG = re.compile(r"chore(\([^)]*\))?: release ")

Version = tuple[int, int, int]


class BumpError(Exception):
    """The bump cannot be performed; the message tells the user what to change."""


def parse_version(text: str) -> Version:
    """Return ``(major, minor, patch)`` for a plain ``X.Y.Z``; pre-release and local parts are refused."""
    match = VERSION.fullmatch(text)
    if match is None:
        raise BumpError(f"{text!r} is not a version of the form X.Y.Z")
    major, minor, patch = (int(part) for part in match.groups())
    return major, minor, patch


def next_version(current: Version, request: str) -> Version:
    """Resolve ``major``/``minor``/``patch`` or an explicit ``X.Y.Z``; it must be greater than ``current``."""
    major, minor, patch = current
    steps: dict[str, Version] = {
        "major": (major + 1, 0, 0),
        "minor": (major, minor + 1, 0),
        "patch": (major, minor, patch + 1),
    }
    new = steps[request] if request in steps else parse_version(request)
    if new <= current:
        raise BumpError(f"the new version {format_version(new)} must be greater than {format_version(current)}")
    return new


def format_version(version: Version) -> str:
    return ".".join(str(part) for part in version)


def _single(pattern: re.Pattern[str], text: str, name: str) -> str:
    found = pattern.findall(text)
    if len(found) != 1:
        raise BumpError(f"expected exactly one version line in {name}, found {len(found)}")
    return found[0]


def read_version(root: Path) -> Version:
    """The versions in ``pyproject.toml`` and ``_version.py``; they must agree before a bump starts."""
    project = _single(PYPROJECT_LINE, (root / "pyproject.toml").read_text(), "pyproject.toml")
    fallback = _single(FALLBACK_LINE, (root / "src/ontolint/_version.py").read_text(), "src/ontolint/_version.py")
    if project != fallback:
        raise BumpError(f"pyproject.toml says {project} but _version.py says {fallback}; make them equal first")
    return parse_version(project)


def _git(root: Path, *args: str) -> str:
    result = subprocess.run(["git", *args], cwd=root, capture_output=True, text=True, check=False)
    if result.returncode != 0:
        raise BumpError(f"git {' '.join(args)} failed: {result.stderr.strip()}")
    return result.stdout


def previous_tag(root: Path, before: Version) -> str | None:
    """The highest ``vX.Y.Z`` tag below ``before``, or ``None`` when there is none."""
    tags = [t for t in _git(root, "tag", "--list", "v*.*.*").split() if TAG.fullmatch(t)]
    known = [t for t in tags if parse_version(t[1:]) < before]
    return max(known, key=lambda t: parse_version(t[1:]), default=None)


@dataclass(frozen=True)
class Entry:
    kind: str
    text: str
    short_hash: str


def classify(subject: str, short_hash: str) -> Entry | None:
    """Map one commit subject to a changelog entry, or ``None`` for release and merge commits."""
    if NOT_IN_CHANGELOG.match(subject) or subject.startswith("Merge "):
        return None
    match = SUBJECT.fullmatch(subject)
    if match is None:
        return Entry("other", subject, short_hash)
    kind = match["type"]
    text = f"**{match['scope']}:** {match['text']}" if match["scope"] else match["text"]
    if match["bang"]:
        return Entry("breaking", text, short_hash)
    return Entry(kind if kind in {"feat", "fix", "perf", "docs"} else "other", text, short_hash)


def commits_between(root: Path, start: str | None, end: str) -> list[Entry]:
    """Changelog entries for ``start..end`` (or all of ``end`` without a start), oldest first."""
    span = f"{start}..{end}" if start else end
    out = _git(root, "log", "--reverse", "--no-merges", "--format=%h%x1f%s%x1f%b%x1e", span)
    entries: list[Entry] = []
    for record in out.split("\x1e"):
        if not record.strip():
            continue
        short_hash, subject, body = (record.strip("\n").split("\x1f") + ["", ""])[:3]
        entry = classify(subject.strip(), short_hash.strip())
        if entry is not None and "BREAKING CHANGE" in body:
            entry = Entry("breaking", entry.text, entry.short_hash)
        if entry is not None:
            entries.append(entry)
    return entries


def render_section(version: Version, when: date, entries: Sequence[Entry]) -> str:
    """One ``## [X.Y.Z] - date`` section, grouped by kind; empty groups are left out."""
    grouped: dict[str, list[Entry]] = defaultdict(list)
    for entry in entries:
        grouped[entry.kind].append(entry)
    lines = [f"## [{format_version(version)}] - {when.isoformat()}", ""]
    for kind, title in SECTIONS:
        if grouped[kind]:
            lines += [f"### {title}", ""]
            lines += [f"- {e.text} ({e.short_hash})" for e in grouped[kind]]
            lines.append("")
    if not any(grouped.values()):
        lines += ["No notable changes.", ""]
    return "\n".join(lines)


def build_changelog(root: Path, new: Version, today: date) -> str:
    """The new ``CHANGELOG.md``: a prepended section, or a full history built from the tags when absent."""
    path = root / "CHANGELOG.md"
    start = previous_tag(root, new)
    section = render_section(new, today, commits_between(root, start, "HEAD"))
    if path.exists():
        existing = path.read_text()
        if f"## [{format_version(new)}]" in existing:
            raise BumpError(f"CHANGELOG.md already has a section for {format_version(new)}")
        head, _, rest = existing.partition("\n## ")
        return f"{head.rstrip()}\n\n{section}\n" + (f"## {rest}" if rest else "")
    return f"{CHANGELOG_HEADER}\n{section}\n{_history(root, start)}"


def _history(root: Path, start: str | None) -> str:
    """Sections for every released tag up to ``start``, newest first (only used when no changelog exists)."""
    tags = sorted(
        (t for t in _git(root, "tag", "--list", "v*.*.*").split() if TAG.fullmatch(t)),
        key=lambda t: parse_version(t[1:]),
    )
    sections: list[str] = []
    for index, tag in enumerate(tags):
        if start is None or parse_version(tag[1:]) > parse_version(start[1:]):
            continue
        when = date.fromisoformat(_git(root, "log", "-1", "--format=%cs", tag).strip())
        sections.append(
            render_section(parse_version(tag[1:]), when, commits_between(root, tags[index - 1] if index else None, tag))
        )
    return "\n".join(reversed(sections))


@dataclass(frozen=True)
class Plan:
    old: Version
    new: Version
    files: dict[Path, str]  # path -> new content, without the lock file


def _pin_action(workflow: str, version: str) -> str:
    """The release workflow with its one ``uses: arnaudgelas/ontolint@vX.Y.Z`` moved to ``version``."""
    if len(ACTION_PIN.findall(workflow)) != 1:
        raise BumpError(f"expected exactly one pin of the Action in {RELEASE_WORKFLOW}")
    return ACTION_PIN.sub(version, workflow)


def plan_bump(root: Path, request: str, today: date, *, changelog: bool = True) -> Plan:
    """Compute every edit without touching the disk."""
    old = read_version(root)
    new = next_version(old, request)
    text = format_version(new)
    pyproject, fallback = root / "pyproject.toml", root / "src/ontolint/_version.py"
    files = {
        pyproject: PYPROJECT_LINE.sub(f'version = "{text}"', pyproject.read_text(), count=1),
        fallback: FALLBACK_LINE.sub(f'FALLBACK_VERSION = "{text}"', fallback.read_text(), count=1),
    }
    release = root / RELEASE_WORKFLOW
    if release.exists():
        files[release] = _pin_action(release.read_text(), text)
    if changelog:
        files[root / "CHANGELOG.md"] = build_changelog(root, new, today)
    return Plan(old, new, files)


def require_clean_tree(root: Path) -> None:
    dirty = _git(root, "status", "--porcelain", "--untracked-files=no").strip()
    if dirty:
        raise BumpError("the working tree has uncommitted changes to tracked files; commit or stash them first")


def refresh_lock(root: Path) -> None:
    """Let uv record the new project version in ``uv.lock`` (no other pin is upgraded)."""
    result = subprocess.run(["uv", "lock"], cwd=root, capture_output=True, text=True, check=False)
    if result.returncode != 0:
        raise BumpError(f"uv lock failed: {result.stderr.strip()}")


def apply(  # noqa: PLR0913 -- one keyword per independent switch; the CLI exposes them.
    root: Path,
    request: str,
    *,
    today: date | None = None,
    dry_run: bool = False,
    changelog: bool = True,
    lock: Callable[[Path], None] | None = refresh_lock,
) -> Plan:
    """Validate, then write the edits (unless ``dry_run``); the tree must be clean before it starts."""
    require_clean_tree(root)
    plan = plan_bump(root, request, today or date.today(), changelog=changelog)
    if not dry_run:
        for path, content in plan.files.items():
            path.write_text(content)
        if lock is not None:
            lock(root)
    return plan


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("version", help="major, minor, patch or an explicit X.Y.Z greater than the current one")
    parser.add_argument("--dry-run", action="store_true", help="show what would change and write nothing")
    parser.add_argument("--no-changelog", action="store_true", help="leave CHANGELOG.md alone")
    args = parser.parse_args(argv)
    root = Path(__file__).resolve().parent.parent
    try:
        plan = apply(root, args.version, dry_run=args.dry_run, changelog=not args.no_changelog)
    except BumpError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    verb = "would change" if args.dry_run else "changed"
    print(f"{format_version(plan.old)} -> {format_version(plan.new)}; {verb}:")
    for path in plan.files:
        print(f"  {path.relative_to(root)}")
    if not args.dry_run:
        print("  uv.lock")
        tag = f"v{format_version(plan.new)}"
        release = f"chore: release {format_version(plan.new)}"
        print(f"Review with git diff, then: git commit -am '{release}' && git tag -a {tag}")
        print("Pushing the tag publishes to PyPI; nothing was committed, tagged or pushed.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
